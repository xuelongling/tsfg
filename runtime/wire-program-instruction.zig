// No opaque kind payload is accepted. Exact prefix operands and Source anchors
// live in Instruction; each union arm retains that opcode's complete suffix.
// Constant bits stay u64, including f32 high-zero checks performed by a future
// independent validator. String constants retain their UTF16 code units.
pub const Data = union(Opcode) {
    @"const_i32": u64,
    @"return": void,
    @"const_bool": bool,
    @"add": void,
    @"sub": void,
    @"mul": void,
    @"div": void,
    @"rem": void,
    @"shl": void,
    @"shr": void,
    @"ushr": void,
    @"and": void,
    @"or": void,
    @"xor": void,
    @"neg": void,
    @"not": void,
    @"bool_not": void,
    @"eq": void,
    @"ne": void,
    @"lt": void,
    @"le": void,
    @"gt": void,
    @"ge": void,
    @"br": struct { @"destination": t.BlockRef },
    @"cond_br": struct { @"true_destination": t.BlockRef, @"false_destination": t.BlockRef, @"true_count": u16 },
    @"fuel": struct { @"event": FuelEvent },
    @"call": struct { @"callee": t.FunctionRef },
    @"const_integer": u64,
    @"global_load": struct { @"global": t.GlobalRef },
    @"global_store": struct { @"global": t.GlobalRef, @"initialize": bool },
    @"authorized_host": struct { @"host": t.HostRef },
    @"const_float": u64,
    @"pos": void,
    @"string_constant": []const u16,
    @"string_concat": void,
    @"string_length": void,
    @"string_codeunit": void,
    @"string_slice": void,
    @"string_compare": void,
    @"convert_checked": void,
    @"convert_wrap": void,
    @"reinterpret": void,
    @"domain_literal": struct { @"actual_type": t.TypeRef },
    @"domain_view": struct { @"static_view": t.TypeRef },
    @"domain_copy": struct { @"static_view": t.TypeRef },
    @"domain_refine": struct { @"static_view": t.TypeRef, @"absent_type": t.TypeRef, @"predicate": t.RegisterRef, @"selected_successor": t.BlockRef, @"equal": bool },
    @"domain_read_span": struct { @"static_view": t.TypeRef },
    @"domain_presence_equal": struct { @"operator": EqualityKind },
    @"domain_identity_equal": struct { @"operator": EqualityKind },
    @"domain_array_length": void,
    @"domain_array_create": struct { @"actual_array_type": t.TypeRef, @"element_domain": t.DomainRef, @"owner": []const u8 },
    @"domain_array_read": struct { @"element_view": t.TypeRef },
    @"domain_array_store": struct { @"receiver_view": t.TypeRef, @"rhs_view": t.TypeRef },
    @"domain_array_resize": struct { @"receiver_view": t.TypeRef },
    @"domain_field_read": struct { @"receiver_view": t.TypeRef, @"member": t.FieldRef, @"dispatch": t.DispatchRef },
    @"domain_field_store": struct { @"receiver_view": t.TypeRef, @"member": t.FieldRef, @"dispatch": t.DispatchRef, @"rhs_view": t.TypeRef },
    @"domain_construct": struct { @"construction": t.ConstructionRef, @"actual_type": t.TypeRef },
    @"domain_super": struct { @"construction": t.ConstructionRef },
    @"domain_initialize_fields": struct { @"construction": t.ConstructionRef, @"owner_type": t.TypeRef },
    @"domain_field_define": struct { @"construction": t.ConstructionRef, @"owner_type": t.TypeRef, @"field": t.FieldRef, @"ordinal": u16 },
    @"domain_field_initialize": struct { @"construction": t.ConstructionRef, @"owner_type": t.TypeRef, @"field": t.FieldRef, @"ordinal": u16 },
    @"domain_method_call": struct { @"receiver_view": t.TypeRef, @"member": t.MethodRef, @"dispatch": t.DispatchRef },
    @"domain_member_present": struct { @"receiver_view": t.TypeRef, @"member": t.FieldRef, @"dispatch": t.DispatchRef },
    @"domain_numeric_use": struct { @"target_type": t.TypeRef, @"numeric_operator": Opcode, @"numeric_arity": u8, @"numeric_operand": u8, @"numeric_group": []const u8, @"normal_successor": t.BlockRef },
    @"environment_alloc": struct { @"environment": t.EnvironmentRef, @"anchor_kind": EnvironmentAnchor },
    @"environment_parent": void,
    @"environment_init": struct { @"slot": t.EnvironmentSlotRef, @"anchor_kind": EnvironmentAnchor },
    @"environment_load": struct { @"slot": t.EnvironmentSlotRef },
    @"environment_store": struct { @"slot": t.EnvironmentSlotRef },
    @"function_make": struct { @"function": t.FunctionRef },
    @"function_call": struct { @"signature": t.TypeRef },
    @"eh_cell": struct { @"binding": t.CellRef },
    @"eh_enter": struct { @"scope": t.ScopeRef },
    @"eh_store": struct { @"binding": t.CellRef, @"initialize": bool },
    @"eh_load": struct { @"binding": t.CellRef },
    @"eh_project": struct { @"binding": t.CellRef, @"target_type": t.TypeRef },
    @"eh_pack": struct { @"payload_type": t.TypeRef },
    @"eh_type_test": struct { @"tag": TypeofTag, @"operator": EqualityKind, @"order": TypeofOrder },
    @"eh_presence_widen": void,
    @"eh_construct": struct { @"owner": t.TypeRef, @"constructor": t.ConstructionRef },
    @"eh_field_initialize": struct { @"field": t.FieldRef },
    @"eh_field_read": []const t.FieldRef,
    @"eh_function": struct { @"function": t.FunctionRef },
    @"eh_publish": struct { @"module": t.ModuleRef },
    @"eh_invoke": struct { @"callee": t.FunctionRef, @"normal": t.BlockRef, @"exceptional": t.BlockRef },
    @"eh_invoke_indirect": struct { @"callable": t.TypeRef, @"normal": t.BlockRef, @"exceptional": t.BlockRef },
    @"eh_route": struct { @"completion": Completion, @"scope": t.ScopeRef, @"successor": t.BlockRef },
    @"eh_raise": void,
