// R04 Single-Source-of-Truth Binding Generator: `.tsfgabi` -> Zig, TypeScript (.d.ts), and C11 (.h).
// Generates static layout/offset/enum assertions and runtime ABI hash/triple handshake on both sides.
import { canonical } from './r04-identity.mjs';

const ZIG_SCALARS = Object.freeze({
  bool: 'u8', // ABI bool is fixed u8 (0 | 1) per tsfg-architecture.md
  f32: 'f32',
  f64: 'f64',
  i16: 'i16',
  i32: 'i32',
  i64: 'i64',
  i8: 'i8',
  isize: 'isize',
  u16: 'u16',
  u32: 'u32',
  u64: 'u64',
  u8: 'u8',
  usize: 'usize',
  void: 'void',
});

const C_SCALARS = Object.freeze({
  bool: 'uint8_t',
  f32: 'float',
  f64: 'double',
  i16: 'int16_t',
  i32: 'int32_t',
  i64: 'int64_t',
  i8: 'int8_t',
  isize: 'intptr_t',
  u16: 'uint16_t',
  u32: 'uint32_t',
  u64: 'uint64_t',
  u8: 'uint8_t',
  usize: 'uintptr_t',
  void: 'void',
});

function sortByDependency(types) {
  const map = new Map(types.map((t) => [t.name, t]));
  const visited = new Set();
  const order = [];
  const visit = (t) => {
    if (!t || visited.has(t.name)) return;
    visited.add(t.name);
    if (t.kind === 'struct') {
      for (const f of t.fields) visit(map.get(f.type));
    } else if (t.kind === 'tagged_union') {
      visit(map.get(t.tagType));
      for (const v of t.variants ?? []) visit(map.get(v.type));
    } else if (t.kind === 'span' || t.kind === 'read_span') {
      visit(map.get(t.elementType));
    } else if (t.kind === 'fn_ptr') {
      visit(map.get(t.returnType));
      for (const p of t.paramTypes ?? []) visit(map.get(p));
    }
    order.push(t);
  };
  for (const t of types) visit(t);
  return order;
}

function zigTypeName(name, typeMap) {
  if (ZIG_SCALARS[name]) return ZIG_SCALARS[name];
  const t = typeMap.get(name);
  if (!t) throw new TypeError(`r04-bindgen: unknown Zig type ${name}`);
  return t.name;
}

function cTypeName(name, typeMap) {
  if (C_SCALARS[name]) return C_SCALARS[name];
  const t = typeMap.get(name);
  if (!t) throw new TypeError(`r04-bindgen: unknown C type ${name}`);
  return t.name;
}

/**
 * Generate Zig `extern` bindings + `comptime` layout/offset/enum assertions + runtime handshake.
 */
export function generateZigBindings(abiPayload, opts = {}) {
  const typeMap = new Map(abiPayload.types.map((t) => [t.name, t]));
  const ordered = sortByDependency(abiPayload.types).filter((t) => t.kind !== 'scalar');
  const lines = [
    '// SPDX-License-Identifier: MIT',
    '// GENERATED BY tsfg R04 ABI Bindgen — DO NOT HAND-EDIT LAYOUTS.',
    'const std = @import("std");',
    '',
    `pub const TSFG_ABI_HASH = ${JSON.stringify(abiPayload.abiHash)};`,
    `pub const TSFG_TARGET_TRIPLE = ${JSON.stringify(abiPayload.target.triple)};`,
    `pub const TSFG_LLVM_DATALAYOUT = ${JSON.stringify(abiPayload.target.llvmDataLayout)};`,
    '',
    'pub fn verifyAbiHandshake(actual_hash: []const u8, actual_triple: []const u8) bool {',
    '    return std.mem.eql(u8, actual_hash, TSFG_ABI_HASH) and std.mem.eql(u8, actual_triple, TSFG_TARGET_TRIPLE);',
    '}',
    '',
    'pub export fn tsfg_abi_verify_handshake(',
    '    actual_hash_ptr: [*]const u8,',
    '    actual_hash_len: usize,',
    '    actual_triple_ptr: [*]const u8,',
    '    actual_triple_len: usize,',
    ') callconv(.c) i32 {',
    '    const ok = verifyAbiHandshake(actual_hash_ptr[0..actual_hash_len], actual_triple_ptr[0..actual_triple_len]);',
    '    return if (ok) 1 else 0;',
    '}',
    '',
  ];

  const asserts = [];

  for (const t of ordered) {
    if (t.kind === 'enum') {
      const backing = ZIG_SCALARS[t.underlyingType];
      lines.push(`pub const ${t.name} = enum(${backing}) {`);
      for (const v of t.variants) {
        lines.push(`    ${v.name} = ${v.value},`);
      }
      lines.push('};');
      lines.push('');
      asserts.push(`    if (@sizeOf(${t.name}) != ${t.byteSize}) @compileError("${t.name} size mismatch");`);
      asserts.push(`    if (@alignOf(${t.name}) != ${t.align}) @compileError("${t.name} align mismatch");`);
      asserts.push(`    if (@typeInfo(${t.name}).@"enum".tag_type != ${backing}) @compileError("${t.name} enum backing mismatch");`);
    } else if (t.kind === 'handle') {
      lines.push(`pub const ${t.name} = extern struct {`);
      lines.push('    index: u32,');
      lines.push('    generation: u32,');
      lines.push('};');
      lines.push('');
      asserts.push(`    if (@sizeOf(${t.name}) != ${t.byteSize}) @compileError("${t.name} size mismatch");`);
      asserts.push(`    if (@alignOf(${t.name}) != ${t.align}) @compileError("${t.name} align mismatch");`);
      asserts.push(`    if (@offsetOf(${t.name}, "index") != 0) @compileError("${t.name}.index offset mismatch");`);
      asserts.push(`    if (@offsetOf(${t.name}, "generation") != 4) @compileError("${t.name}.generation offset mismatch");`);
    } else if (t.kind === 'span' || t.kind === 'read_span') {
      const elemZ = zigTypeName(t.elementType, typeMap);
      const ptrTy = t.kind === 'read_span' ? `[*]const ${elemZ}` : `[*]${elemZ}`;
      lines.push(`pub const ${t.name} = extern struct {`);
      lines.push(`    ptr: ${ptrTy},`);
      lines.push('    len: usize,');
      lines.push('};');
      lines.push('');
      asserts.push(`    if (@sizeOf(${t.name}) != ${t.byteSize}) @compileError("${t.name} size mismatch");`);
      asserts.push(`    if (@alignOf(${t.name}) != ${t.align}) @compileError("${t.name} align mismatch");`);
      asserts.push(`    if (@offsetOf(${t.name}, "ptr") != 0) @compileError("${t.name}.ptr offset mismatch");`);
      asserts.push(`    if (@offsetOf(${t.name}, "len") != ${t.fields[1].offset}) @compileError("${t.name}.len offset mismatch");`);
    } else if (t.kind === 'string_view') {
      lines.push(`pub const ${t.name} = extern struct {`);
      lines.push('    ptr: [*]const u8,');
      lines.push('    len: usize,');
      lines.push('};');
      lines.push('');
      asserts.push(`    if (@sizeOf(${t.name}) != ${t.byteSize}) @compileError("${t.name} size mismatch");`);
      asserts.push(`    if (@alignOf(${t.name}) != ${t.align}) @compileError("${t.name} align mismatch");`);
    } else if (t.kind === 'fn_ptr') {
      const pList = t.paramTypes.map((pn) => zigTypeName(pn, typeMap)).join(', ');
      const retZ = zigTypeName(t.returnType, typeMap);
      lines.push(`pub const ${t.name} = ?*const fn (${pList}) callconv(.c) ${retZ};`);
      lines.push('');
      asserts.push(`    if (@sizeOf(${t.name}) != ${t.byteSize}) @compileError("${t.name} size mismatch");`);
      asserts.push(`    if (@alignOf(${t.name}) != ${t.align}) @compileError("${t.name} align mismatch");`);
    } else if (t.kind === 'struct') {
      lines.push(`pub const ${t.name} = extern struct {`);
      for (const f of t.fields) {
        lines.push(`    ${f.name}: ${zigTypeName(f.type, typeMap)},`);
      }
      lines.push('};');
      lines.push('');
      asserts.push(`    if (@sizeOf(${t.name}) != ${t.byteSize}) @compileError("${t.name} size mismatch");`);
      asserts.push(`    if (@alignOf(${t.name}) != ${t.align}) @compileError("${t.name} align mismatch");`);
      for (const f of t.fields) {
        asserts.push(`    if (@offsetOf(${t.name}, ${JSON.stringify(f.name)}) != ${f.offset}) @compileError("${t.name}.${f.name} offset mismatch");`);
      }
    } else if (t.kind === 'tagged_union') {
      const tagZ = ZIG_SCALARS[t.tagType];
      lines.push(`pub const ${t.name}Payload = extern union {`);
      for (const v of t.variants) {
        lines.push(`    ${v.name}: ${zigTypeName(v.type, typeMap)},`);
      }
      lines.push('};');
      lines.push(`pub const ${t.name} = extern struct {`);
      lines.push(`    tag: ${tagZ},`);
      lines.push(`    payload: ${t.name}Payload,`);
      lines.push('};');
      lines.push('');
      asserts.push(`    if (@sizeOf(${t.name}) != ${t.byteSize}) @compileError("${t.name} size mismatch");`);
      asserts.push(`    if (@alignOf(${t.name}) != ${t.align}) @compileError("${t.name} align mismatch");`);
      asserts.push(`    if (@offsetOf(${t.name}, "tag") != 0) @compileError("${t.name}.tag offset mismatch");`);
      asserts.push(`    if (@offsetOf(${t.name}, "payload") != ${t.payloadOffset}) @compileError("${t.name}.payload offset mismatch");`);
    }
  }

  if (opts.emitExternFunctions !== false && (abiPayload.functions ?? []).length > 0) {
    for (const fn of abiPayload.functions) {
      const pList = fn.params.map((p) => `${p.name}: ${zigTypeName(p.type, typeMap)}`).join(', ');
      const retZ = zigTypeName(fn.returnClass.type, typeMap);
      lines.push(`pub extern fn ${fn.symbol}(${pList}) callconv(.c) ${retZ};`);
    }
    lines.push('');
  }

  lines.push('comptime {');
  lines.push(...asserts);
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

/**
 * Generate C11 header (`.h`) with `typedef`s, prototypes, and `_Static_assert`s.
 */
export function generateCHeader(abiPayload) {
  const typeMap = new Map(abiPayload.types.map((t) => [t.name, t]));
  const ordered = sortByDependency(abiPayload.types).filter((t) => t.kind !== 'scalar');
  const lines = [
    '/* SPDX-License-Identifier: MIT */',
    '/* GENERATED BY tsfg R04 ABI Bindgen — DO NOT HAND-EDIT LAYOUTS. */',
    '#pragma once',
    '#include <stdalign.h>',
    '#include <stddef.h>',
    '#include <stdint.h>',
    '',
    `#define TSFG_ABI_HASH ${JSON.stringify(abiPayload.abiHash)}`,
    `#define TSFG_TARGET_TRIPLE ${JSON.stringify(abiPayload.target.triple)}`,
    '',
    'extern int32_t tsfg_abi_verify_handshake(const uint8_t *hash_ptr, size_t hash_len, const uint8_t *triple_ptr, size_t triple_len);',
    '',
  ];

  for (const t of ordered) {
    if (t.kind === 'enum') {
      const backing = C_SCALARS[t.underlyingType];
      lines.push(`typedef ${backing} ${t.name};`);
      for (const v of t.variants) {
        lines.push(`#define ${t.name}_${v.name} ((${t.name})${v.value})`);
      }
      lines.push(`_Static_assert(sizeof(${t.name}) == ${t.byteSize}, "${t.name} size mismatch");`);
      lines.push(`_Static_assert(alignof(${t.name}) == ${t.align}, "${t.name} align mismatch");`);
      lines.push('');
    } else if (t.kind === 'handle') {
      lines.push(`typedef struct ${t.name} {`);
      lines.push('  uint32_t index;');
      lines.push('  uint32_t generation;');
      lines.push(`} ${t.name};`);
      lines.push(`_Static_assert(sizeof(${t.name}) == ${t.byteSize}, "${t.name} size mismatch");`);
      lines.push(`_Static_assert(alignof(${t.name}) == ${t.align}, "${t.name} align mismatch");`);
      lines.push(`_Static_assert(offsetof(${t.name}, index) == 0, "${t.name}.index offset");`);
      lines.push(`_Static_assert(offsetof(${t.name}, generation) == 4, "${t.name}.generation offset");`);
      lines.push('');
    } else if (t.kind === 'span' || t.kind === 'read_span') {
      const elemC = cTypeName(t.elementType, typeMap);
      const q = t.kind === 'read_span' ? 'const ' : '';
      lines.push(`typedef struct ${t.name} {`);
      lines.push(`  ${q}${elemC} *ptr;`);
      lines.push('  uintptr_t len;');
      lines.push(`} ${t.name};`);
      lines.push(`_Static_assert(sizeof(${t.name}) == ${t.byteSize}, "${t.name} size mismatch");`);
      lines.push(`_Static_assert(alignof(${t.name}) == ${t.align}, "${t.name} align mismatch");`);
      lines.push(`_Static_assert(offsetof(${t.name}, len) == ${t.fields[1].offset}, "${t.name}.len offset");`);
      lines.push('');
    } else if (t.kind === 'string_view') {
      lines.push(`typedef struct ${t.name} {`);
      lines.push('  const uint8_t *ptr;');
      lines.push('  uintptr_t len;');
      lines.push(`} ${t.name};`);
      lines.push(`_Static_assert(sizeof(${t.name}) == ${t.byteSize}, "${t.name} size mismatch");`);
      lines.push(`_Static_assert(alignof(${t.name}) == ${t.align}, "${t.name} align mismatch");`);
      lines.push('');
    } else if (t.kind === 'fn_ptr') {
      const pList = t.paramTypes.length > 0 ? t.paramTypes.map((pn) => cTypeName(pn, typeMap)).join(', ') : 'void';
      const retC = cTypeName(t.returnType, typeMap);
      lines.push(`typedef ${retC} (*${t.name})(${pList});`);
      lines.push(`_Static_assert(sizeof(${t.name}) == ${t.byteSize}, "${t.name} size mismatch");`);
      lines.push(`_Static_assert(alignof(${t.name}) == ${t.align}, "${t.name} align mismatch");`);
      lines.push('');
    } else if (t.kind === 'struct') {
      lines.push(`typedef struct ${t.name} {`);
      for (const f of t.fields) {
        lines.push(`  ${cTypeName(f.type, typeMap)} ${f.name};`);
      }
      lines.push(`} ${t.name};`);
      lines.push(`_Static_assert(sizeof(${t.name}) == ${t.byteSize}, "${t.name} size mismatch");`);
      lines.push(`_Static_assert(alignof(${t.name}) == ${t.align}, "${t.name} align mismatch");`);
      for (const f of t.fields) {
        lines.push(`_Static_assert(offsetof(${t.name}, ${f.name}) == ${f.offset}, "${t.name}.${f.name} offset");`);
      }
      lines.push('');
    } else if (t.kind === 'tagged_union') {
      const tagC = C_SCALARS[t.tagType];
      lines.push(`typedef union ${t.name}Payload {`);
      for (const v of t.variants) {
        lines.push(`  ${cTypeName(v.type, typeMap)} ${v.name};`);
      }
      lines.push(`} ${t.name}Payload;`);
      lines.push(`typedef struct ${t.name} {`);
      lines.push(`  ${tagC} tag;`);
      lines.push(`  ${t.name}Payload payload;`);
      lines.push(`} ${t.name};`);
      lines.push(`_Static_assert(sizeof(${t.name}) == ${t.byteSize}, "${t.name} size mismatch");`);
      lines.push(`_Static_assert(alignof(${t.name}) == ${t.align}, "${t.name} align mismatch");`);
      lines.push(`_Static_assert(offsetof(${t.name}, payload) == ${t.payloadOffset}, "${t.name}.payload offset");`);
      lines.push('');
    }
  }

  for (const fn of abiPayload.functions ?? []) {
    const pList = fn.params.length > 0
      ? fn.params.map((p) => `${cTypeName(p.type, typeMap)} ${p.name}`).join(', ')
      : 'void';
    const retC = cTypeName(fn.returnClass.type, typeMap);
    lines.push(`extern ${retC} ${fn.symbol}(${pList});`);
  }
  lines.push('');
  return lines.join('\n');
}

/**
 * Generate tsfg TypeScript declarations (`.d.ts`) + embedded static ABI contract assertions.
 */
export function generateTsDeclarations(abiPayload) {
  const ordered = sortByDependency(abiPayload.types).filter((t) => t.kind !== 'scalar');
  const lines = [
    '// SPDX-License-Identifier: MIT',
    '// GENERATED BY tsfg R04 ABI Bindgen — DO NOT HAND-EDIT LAYOUTS.',
    `export declare const TSFG_ABI_HASH: ${JSON.stringify(abiPayload.abiHash)};`,
    `export declare const TSFG_TARGET_TRIPLE: ${JSON.stringify(abiPayload.target.triple)};`,
    `export declare const TSFG_ABI_CALLING_CONVENTION: ${JSON.stringify(abiPayload.callingConvention)};`,
    '',
  ];

  for (const t of ordered) {
    if (t.kind === 'enum') {
      lines.push(`/** @abi enum underlying=${t.underlyingType} size=${t.byteSize} align=${t.align} */`);
      lines.push(`export declare enum ${t.name} {`);
      for (const v of t.variants) lines.push(`  ${v.name} = ${v.value},`);
      lines.push('}');
      lines.push('');
    } else if (t.kind === 'handle') {
      lines.push(`/** @abi handle size=${t.byteSize} align=${t.align} targetTypeId=${t.targetTypeId} */`);
      lines.push(`export interface ${t.name} { readonly index: u32; readonly generation: u32; }`);
      lines.push('');
    } else if (t.kind === 'span' || t.kind === 'read_span') {
      lines.push(`/** @abi ${t.kind} size=${t.byteSize} align=${t.align} */`);
      lines.push(`export type ${t.name} = ${t.kind === 'read_span' ? 'ReadSpan' : 'Span'}<${t.elementType}>;`);
      lines.push('');
    } else if (t.kind === 'string_view') {
      lines.push(`/** @abi string_view size=${t.byteSize} align=${t.align} */`);
      lines.push(`export interface ${t.name} { readonly ptr: usize; readonly len: usize; }`);
      lines.push('');
    } else if (t.kind === 'fn_ptr') {
      const pList = t.paramTypes.map((p, i) => `a${i}: ${p}`).join(', ');
      lines.push(`/** @abi fn_ptr signatureHash=${t.signatureHash} */`);
      lines.push(`export type ${t.name} = (${pList}) => ${t.returnType};`);
      lines.push('');
    } else if (t.kind === 'struct') {
      const offSummary = t.fields.map((f) => `${f.name}@${f.offset}`).join(', ');
      lines.push(`/** @abi struct size=${t.byteSize} align=${t.align} offsets=[${offSummary}] */`);
      lines.push(`export interface ${t.name} {`);
      for (const f of t.fields) {
        lines.push(`  ${f.readonly ? 'readonly ' : ''}${f.name}: ${f.type};`);
      }
      lines.push('}');
      lines.push('');
    } else if (t.kind === 'tagged_union') {
      lines.push(`/** @abi tagged_union tag=${t.tagType} payloadOffset=${t.payloadOffset} size=${t.byteSize} align=${t.align} */`);
      const arms = t.variants.map((v) => `{ readonly tag: ${v.tagValue}; readonly ${v.name}: ${v.type} }`).join(' | ');
      lines.push(`export type ${t.name} = ${arms};`);
      lines.push('');
    }
  }

  for (const fn of abiPayload.functions ?? []) {
    const pList = fn.params.map((p) => `${p.name}: ${p.type}`).join(', ');
    lines.push(`/** @abi fn symbol=${fn.symbol} cc=${fn.callingConvention} ret=${fn.returnClass.mode} functionId=${fn.functionId} */`);
    lines.push(`export declare function ${fn.name}(${pList}): ${fn.returnClass.type};`);
  }
  lines.push('');

  // Embed canonical layout assertion table for static TS-side verification
  const layoutTable = ordered.map((t) => ({
    align: t.align,
    byteSize: t.byteSize,
    fields: t.fields.map((f) => ({ name: f.name, offset: f.offset, type: f.type })),
    kind: t.kind,
    name: t.name,
  }));
  lines.push(`export declare const TSFG_ABI_LAYOUT_ASSERTIONS: ${JSON.stringify(canonical(layoutTable))};`);
  lines.push('');
  return lines.join('\n');
}
