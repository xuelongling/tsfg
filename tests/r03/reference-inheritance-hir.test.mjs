import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { decodeReferenceFacts } from '../../compiler/reference-facts.mjs';
import { buildReferenceHir, readReferenceHir, printReferenceHir } from '../../compiler/reference-hir.mjs';
import { sha256 } from '../../compiler/identity.mjs';
const fixture = name => new URL('./fixtures/reference-source/' + name, import.meta.url);
test('official inheritance bytes retain successful-super initialization and dispatch targets', async () => {
  const bytes = await readFile(fixture('inheritance.facts.json'));
  assert.equal(sha256(bytes), 'sha256:35c6b595bf1cac693089749fde20f48aeaaed83b2235e0e58428d9200b8b678d');
  const binding = JSON.parse(await readFile(fixture('inheritance.binding.json'), 'utf8'));
  const facts = decodeReferenceFacts(bytes, binding), hir = buildReferenceHir(facts);
  const [base, derived] = hir.classes;
  assert.equal(base.name, 'Base'); assert.equal(derived.name, 'Derived'); assert.equal(derived.base, base.id);
  assert.notEqual(base.runtimeKey, derived.runtimeKey);
  assert.equal(base.fields[0].ordinal, 0); assert.equal(derived.fields[0].ordinal, 0);
  const [observe, baseTouch] = base.methods, [derivedTouch, directBaseTouch] = derived.methods;
  assert.equal(observe.name, 'observe'); assert.equal(baseTouch.name, 'touch');
  assert.equal(derivedTouch.overrideTarget, baseTouch.id);
  assert.deepEqual(base.constructor.initializationBoundary, { kind: 'entry' });
  assert.deepEqual(base.constructor.initializationFields, [base.fields[0].id]);
  const escape = base.constructor.body[1].expression;
  assert.equal(escape.kind, 'ref.method.call'); assert.equal(escape.dispatch, 'virtual');
  assert.equal(escape.staticTarget, observe.id);
  const argument = escape.arguments[0];
  assert.equal(argument.kind, 'ref.view'); assert.equal(argument.sourceType, base.thisType);
  assert.equal(argument.targetType, base.instanceType); assert.equal(argument.value.kind, 'ref.this');
  assert.equal(argument.value.symbol, base.symbol);
  assert.equal(argument.members.length, base.fields.length + base.methods.length);
  const earlyVirtual = base.constructor.body[2].expression;
  assert.equal(earlyVirtual.kind, 'ref.method.call'); assert.equal(earlyVirtual.dispatch, 'virtual');
  // Keep the official static target. Dynamic override selection belongs to the
  // actual allocation class at execution, including legal construction calls.
  assert.equal(earlyVirtual.staticTarget, baseTouch.id);
  const constructor = derived.constructor, superCall = constructor.body[0].expression;
  assert.equal(superCall.kind, 'ref.super.construct');
  assert.equal(superCall.id, constructor.superCall);
  assert.equal(superCall.dispatch, 'direct-base-constructor');
  assert.equal(superCall.staticTarget, base.constructor.id);
  assert.equal(superCall.type, 't:void'); assert.equal(superCall.resolvedSignature.return, base.instanceType);
  assert.equal(superCall.receiver.kind, 'ref.super'); assert.equal(superCall.receiver.symbol, base.symbol);
  assert.equal(superCall.arguments[0].symbol, constructor.signature.parameters[0].symbol);
  assert.equal(constructor.initializationPhase, 'after-successful-super');
  assert.deepEqual(constructor.initializationBoundary, { kind: 'successful-return', expressionId: superCall.id });
  assert.deepEqual(constructor.initializationFields, [derived.fields[0].id]);
  assert.equal(derived.fields[0].initializer.kind, 'scalar.literal.unresolved');
  const ownStore = constructor.body[1].expression;
  assert.equal(ownStore.kind, 'ref.field.write'); assert.equal(ownStore.left.symbol, derived.fields[0].symbol);
  assert.equal(ownStore.right.kind, 'ref.method.call'); assert.equal(ownStore.right.staticTarget, derivedTouch.id);
  const inheritedRead = derivedTouch.body[0].expression;
  assert.equal(inheritedRead.kind, 'ref.field.read'); assert.equal(inheritedRead.symbol, base.fields[0].symbol);
  assert.equal(inheritedRead.receiver.symbol, derived.symbol);
  const direct = directBaseTouch.body[0].expression;
  assert.equal(direct.kind, 'ref.method.call'); assert.equal(direct.dispatch, 'direct-base-method');
  assert.equal(direct.staticTarget, baseTouch.id); assert.equal(direct.receiver.kind, 'ref.super');
  const thisView = hir.types.find(type => type.id === direct.receiver.type);
  assert.equal(thisView.kind, 'class-this-view'); assert.equal(thisView.target, base.instanceType);
  assert.equal(thisView.thisArgument, derived.thisType);
  assert.deepEqual(readReferenceHir(Buffer.from(printReferenceHir(hir))), hir);
});
